impl TokenKind {
    /// Short spelling for diagnostics (`found …`).
    pub fn describe(&self) -> String {
        match self {
            Self::Ident(s) => format!("identifier `{s}`"),
            Self::Keyword(k) => format!("`{}`", k.as_str()),
            Self::IntLit { .. } => "integer literal".into(),
            Self::FloatLit { .. } => "float literal".into(),
            Self::CharLit(_) => "character literal".into(),
            Self::StringLit(_) => "string literal".into(),
            Self::Punct(p) => format!("`{}`", p.as_str()),
            Self::Eof => "end of file".into(),
        }
    }
}
