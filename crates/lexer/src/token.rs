use crate::span::Span;

/// A single lexeme with its source span.
#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}

/// Decoded token kinds for the LeetCode C++ subset.
#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    Ident(String),
    Keyword(Keyword),
    IntLit {
        value: u128,
        suffix: IntSuffix,
        base: IntBase,
    },
    FloatLit {
        value: f64,
        suffix: FloatSuffix,
    },
    CharLit(char),
    StringLit(String),
    Punct(Punct),
    Eof,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum IntBase {
    Decimal,
    Hex,
    Binary,
    Octal,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum IntSuffix {
    #[default]
    None,
    U,
    L,
    Ul,
    Ll,
    Ull,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum FloatSuffix {
    #[default]
    None,
    F,
    L,
}

